// Writes the token tables into docs/guide/themes.md, from the contract, the
// roles and the two themes' files: `bun packages/elements/tools/theme-guide.ts`.
// A unit test fails when the guide is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TOKENS } from "../src/styles/contract.ts";
import { ROLES } from "./roles.ts";
import { identities, type Identity } from "./theme-check.ts";

const STYLES = join(import.meta.dir, "../src/styles");
export const GUIDE = join(import.meta.dir, "../../../docs/guide/themes.md");
const START = "<!-- tokens: generated by packages/elements/tools/theme-guide.ts -->";
const END = "<!-- /tokens -->";

const HEADINGS: Record<keyof typeof TOKENS, string> = {
  type: "Type",
  surfaces: "Surfaces",
  text: "Text",
  edges: "Edges",
  accent: "Accent",
  status: "Status",
  identity: "Identity colours",
  elevation: "Elevation",
  shape: "Shape",
  motion: "Motion",
  toast: "Toasts",
  light: "The lamp",
};

/** A value in full; only an inline image is shortened. */
function cell(v: string | undefined): string {
  if (v === undefined) return "";
  const shown = v.startsWith('url("data:') ? 'url("data:image/svg+xml,…") (an SVG noise filter)' : v.replace(/\s+/g, " ");
  return `\`${shown.replaceAll("|", "\\|")}\``;
}

export function tables(): string {
  const theme = (f: string) => identities(readFileSync(join(STYLES, f), "utf8"))[0] as Identity;
  const lamplight = theme("lamplight.css");
  const harbour = theme("harbour.css");
  const parts: string[] = [];
  for (const [group, names] of Object.entries(TOKENS) as [keyof typeof TOKENS, readonly string[]][]) {
    parts.push(`### ${HEADINGS[group]}`, "", "| Token | Role | Lamplight | Lamplight dark | Harbour | Harbour dark |", "|---|---|---|---|---|---|");
    for (const name of names) {
      const t = `--aster-${name}`;
      parts.push(
        `| \`${t}\` | ${ROLES[name] ?? ""} | ${cell(lamplight.light.get(t))} | ${cell(lamplight.dark.get(t))} | ${cell(harbour.light.get(t))} | ${cell(harbour.dark.get(t))} |`,
      );
    }
    parts.push("");
  }
  return parts.join("\n");
}

/** The guide with its tables brought up to date. */
export function updated(guide: string): string {
  const from = guide.indexOf(START);
  const to = guide.indexOf(END);
  if (from < 0 || to < from) throw new Error(`${GUIDE} needs ${START} … ${END}`);
  return `${guide.slice(0, from + START.length)}\n\n${tables()}\n${guide.slice(to)}`;
}

if (import.meta.main) {
  writeFileSync(GUIDE, updated(readFileSync(GUIDE, "utf8")));
  console.log(`wrote ${GUIDE}`);
}
